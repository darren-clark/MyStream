# Generates the handler-shaped counterparts to the Direct switch-scale servers: same 30 message
# types, but one-line switch arms calling an async generic dispatch that resolves the handler by
# type test - i.e. the MultipleImplementationConnection shape.
param([int]$Count = 30, [int]$FirstTypeByte = 10)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $repoRoot 'ToyStream.Protocol.Benchmark\SwitchScale\ScaleHandlerServers.g.cs'
New-Item -ItemType Directory -Force -Path (Split-Path -Parent $outputPath) | Out-Null

function Write-Server($sb, $className, $armIndexes) {
    [void]$sb.AppendLine("public sealed class $className : IAsyncDisposable")
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine('    private readonly PipeReader reader;')
    [void]$sb.AppendLine('    private readonly PipeWriter writer;')
    [void]$sb.AppendLine('    private readonly CancellationToken cancellationToken;')
    [void]$sb.AppendLine('    private readonly object handler;')
    [void]$sb.AppendLine('    private readonly Task readerTask;')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    public $className(PipeReader reader, PipeWriter writer, object handler, CancellationToken cancellationToken)")
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        this.reader = reader;')
    [void]$sb.AppendLine('        this.writer = writer;')
    [void]$sb.AppendLine('        this.handler = handler;')
    [void]$sb.AppendLine('        this.cancellationToken = cancellationToken;')
    [void]$sb.AppendLine('        this.readerTask = this.Read();')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    private async Task Read()')
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        await Task.Yield();')
    [void]$sb.AppendLine('        var buffer = ReadOnlySequence<byte>.Empty;')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('        try')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('            while (!this.cancellationToken.IsCancellationRequested)')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('#pragma warning disable CA2012')
    [void]$sb.AppendLine('                await (await ReadMessageType().ConfigureAwait(false) switch')
    [void]$sb.AppendLine('                {')

    foreach ($i in $armIndexes) {
        $n = '{0:D2}' -f $i
        $typeByte = $i + $FirstTypeByte
        [void]$sb.AppendLine("                    $typeByte => DispatchRequest<ScaleMessage$n, AcknowledgeMessage>(),")
    }

    [void]$sb.AppendLine('                    _ => throw new InvalidOperationException("Unexpected message type.")')
    [void]$sb.AppendLine('                }).ConfigureAwait(false);')
    [void]$sb.AppendLine('#pragma warning restore CA2012')
    [void]$sb.AppendLine('            }')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('        catch (OperationCanceledException)')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('        return;')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('        [AsyncMethodBuilder(typeof(PoolingAsyncValueTaskMethodBuilder<>))]')
    [void]$sb.AppendLine('        async ValueTask<byte> ReadMessageType()')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('            if (buffer.Length < 1)')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('                var result = await this.reader.ReadAsync(this.cancellationToken).ConfigureAwait(false);')
    [void]$sb.AppendLine('                buffer = result.Buffer;')
    [void]$sb.AppendLine('            }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('            var typeByte = MemoryMarshal.Read<byte>(buffer.Slice(0, 1).FirstSpan);')
    [void]$sb.AppendLine('            buffer = buffer.Slice(1);')
    [void]$sb.AppendLine('            return typeByte;')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('        [AsyncMethodBuilder(typeof(PoolingAsyncValueTaskMethodBuilder))]')
    [void]$sb.AppendLine('        async ValueTask DispatchRequest<TRequestMessage, TResponseMessage>()')
    [void]$sb.AppendLine('            where TRequestMessage : struct, IRequestMessage<TRequestMessage, TResponseMessage>, allows ref struct')
    [void]$sb.AppendLine('            where TResponseMessage : struct, IResponseMessage<TResponseMessage>, allows ref struct')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('            if (this.handler is not IMessageHandler<TRequestMessage, TResponseMessage> messageHandler)')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('                throw new InvalidOperationException("Handler does not implement the required interface.");')
    [void]$sb.AppendLine('            }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('            var primitiveReader = new PrimitiveReader(buffer);')
    [void]$sb.AppendLine('            var read = TRequestMessage.TryRead(ref primitiveReader, out var message, out var bytesToRead);')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('            while (!read)')
    [void]$sb.AppendLine('            {')
    [void]$sb.AppendLine('                this.reader.AdvanceTo(buffer.Start, buffer.End);')
    [void]$sb.AppendLine('                var readResult = await this.reader.ReadAtLeastAsync(bytesToRead, this.cancellationToken).ConfigureAwait(false);')
    [void]$sb.AppendLine('                buffer = readResult.Buffer;')
    [void]$sb.AppendLine('                primitiveReader = new PrimitiveReader(buffer);')
    [void]$sb.AppendLine('                read = TRequestMessage.TryRead(ref primitiveReader, out message, out bytesToRead);')
    [void]$sb.AppendLine('            }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('            buffer = primitiveReader.Remaining;')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('            var responseWriter = new ResponseWriter<TResponseMessage>(this.writer);')
    [void]$sb.AppendLine('            await messageHandler.HandleRequest(ref message, responseWriter).ConfigureAwait(false);')
    [void]$sb.AppendLine('            this.reader.AdvanceTo(buffer.Start);')
    [void]$sb.AppendLine('            await this.writer.FlushAsync(this.cancellationToken).ConfigureAwait(false);')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    public async ValueTask DisposeAsync()')
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        await this.readerTask.ConfigureAwait(false);')
    [void]$sb.AppendLine('        GC.SuppressFinalize(this);')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine('')
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Generated by scripts/gen-scale-handler.ps1. Do not edit.')
[void]$sb.AppendLine('namespace ToyStream.Protocol.Benchmark.SwitchScale;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('using System.Buffers;')
[void]$sb.AppendLine('using System.IO.Pipelines;')
[void]$sb.AppendLine('using System.Runtime.CompilerServices;')
[void]$sb.AppendLine('using System.Runtime.InteropServices;')
[void]$sb.AppendLine('using Messages;')
[void]$sb.AppendLine('using Protocol.Dispatch;')
[void]$sb.AppendLine('using Scale;')
[void]$sb.AppendLine('')

# Handler implementing one IMessageHandler<,> per message type.
[void]$sb.AppendLine('public sealed class ScaleMessageHandler :')
$interfaces = 0..($Count - 1) | ForEach-Object { '    IMessageHandler<ScaleMessage{0:D2}, AcknowledgeMessage>' -f $_ }
[void]$sb.AppendLine(($interfaces -join ",`r`n"))
[void]$sb.AppendLine('{')
[void]$sb.AppendLine('    public long Total;')
[void]$sb.AppendLine('')
0..($Count - 1) | ForEach-Object {
    $n = '{0:D2}' -f $_
    [void]$sb.AppendLine("    public ValueTask HandleRequest(ref readonly ScaleMessage$n message, ResponseWriter<AcknowledgeMessage> responseWriter)")
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        this.Total += message.Value;')
    [void]$sb.AppendLine('        responseWriter.WriteResponse(new AcknowledgeMessage());')
    [void]$sb.AppendLine('        return default;')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
}
[void]$sb.AppendLine('}')
[void]$sb.AppendLine('')

Write-Server $sb 'ScaleHandlerServerWide' (0..($Count - 1))
Write-Server $sb 'ScaleHandlerServerNarrow' @(0)

Set-Content -Path $outputPath -Value $sb.ToString() -Encoding UTF8
Write-Output "Wrote handler, wide ($Count arms) and narrow (1 arm) servers to $outputPath"
