# Regenerates ToyStream.Protocol.Benchmark/Scale/ScaleMessages.g.cs.
# Change $Count to vary how many message types the scale benchmark compiles in.
param([int]$Count = 30, [int]$FirstTypeByte = 10)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $repoRoot 'ToyStream.Protocol.Benchmark\Scale\ScaleMessages.g.cs'

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Generated by scripts/gen-scale-messages.ps1. Do not edit.')
[void]$sb.AppendLine('namespace ToyStream.Protocol.Benchmark.Scale;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('using Messages;')
[void]$sb.AppendLine('')

0..($Count - 1) | ForEach-Object {
    $n = '{0:D2}' -f $_
    $typeByte = $_ + $FirstTypeByte
    [void]$sb.AppendLine("public readonly ref struct ScaleMessage$n : IRequestMessage<ScaleMessage$n, AcknowledgeMessage>")
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine('    public required short Value { get; init; }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    public MessageType Type => (MessageType)$typeByte;")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    static bool IMessage<ScaleMessage$n>.TryRead<TReader>(ref TReader reader, out ScaleMessage$n message, out int bytesToRead)")
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        if (!reader.TryReadInt16(out var value, out bytesToRead))')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('            message = default;')
    [void]$sb.AppendLine('            return false;')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("        message = new ScaleMessage$n { Value = value };")
    [void]$sb.AppendLine('        return true;')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    void IMessage.Write<TWriter>(TWriter writer) => writer.Write(this.Value);')
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine('')
}

Set-Content -Path $outputPath -Value $sb.ToString() -Encoding UTF8
Write-Output "Wrote $Count message types to $outputPath"
