# Regenerates ToyStream.Protocol.Benchmark/Scale/ScaleMessages.g.cs.
# Change $Count to vary how many message types the scale benchmark compiles in.
param([int]$Count = 30, [int]$FirstTypeByte = 10)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$outputPath = Join-Path $repoRoot 'ToyStream.Protocol.Benchmark\Scale\ScaleMessages.g.cs'

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// Generated by scripts/gen-scale-messages.ps1. Do not edit.')
[void]$sb.AppendLine('namespace ToyStream.Protocol.Benchmark.Scale;')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('using Messages;')
[void]$sb.AppendLine('')

0..($Count - 1) | ForEach-Object {
    $n = '{0:D2}' -f $_
    $typeByte = $_ + $FirstTypeByte
    [void]$sb.AppendLine("public readonly ref struct ScaleMessage$n : IRequestMessage<ScaleMessage$n, AcknowledgeMessage>")
    [void]$sb.AppendLine('{')
    [void]$sb.AppendLine('    public required short Value { get; init; }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    public MessageType Type => (MessageType)$typeByte;")
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("    static bool IMessage<ScaleMessage$n>.TryRead<TReader>(ref TReader reader, out ScaleMessage$n message, out int bytesToRead)")
    [void]$sb.AppendLine('    {')
    [void]$sb.AppendLine('        if (!reader.TryReadInt16(out var value, out bytesToRead))')
    [void]$sb.AppendLine('        {')
    [void]$sb.AppendLine('            message = default;')
    [void]$sb.AppendLine('            return false;')
    [void]$sb.AppendLine('        }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine("        message = new ScaleMessage$n { Value = value };")
    [void]$sb.AppendLine('        return true;')
    [void]$sb.AppendLine('    }')
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine('    void IMessage.Write<TWriter>(TWriter writer) => writer.Write(this.Value);')
    [void]$sb.AppendLine('}')
    [void]$sb.AppendLine('')
}

Set-Content -Path $outputPath -Value $sb.ToString() -Encoding UTF8
Write-Output "Wrote $Count message types to $outputPath"

# ScaleServerHandler: one IHandler<T> per message, implemented as plain overloads.
$handlerPath = Join-Path $repoRoot 'ToyStream.Protocol.Benchmark\Scale\ScaleServerHandler.g.cs'
$hb = [System.Text.StringBuilder]::new()
[void]$hb.AppendLine('// Generated by scripts/gen-scale-messages.ps1. Do not edit.')
[void]$hb.AppendLine('namespace ToyStream.Protocol.Benchmark.Scale;')
[void]$hb.AppendLine('')
[void]$hb.AppendLine('/// <summary>')
[void]$hb.AppendLine('/// Implements one IHandler&lt;T&gt; per message it serves. The methods are plain overloads, so each')
[void]$hb.AppendLine('/// one gets a concrete message type to work with.')
[void]$hb.AppendLine('/// </summary>')
[void]$hb.AppendLine('public sealed class ScaleServerHandler :')
$interfaces = 0..($Count - 1) | ForEach-Object { '    IHandler<ScaleMessage{0:D2}>' -f $_ }
[void]$hb.AppendLine(($interfaces -join ",`r`n"))
[void]$hb.AppendLine('{')
[void]$hb.AppendLine('    public long Total { get; private set; }')
[void]$hb.AppendLine('')

0..($Count - 1) | ForEach-Object {
    $n = '{0:D2}' -f $_
    [void]$hb.AppendLine("    public ValueTask Handle(ref readonly ScaleMessage$n message)")
    [void]$hb.AppendLine('    {')
    [void]$hb.AppendLine('        this.Total += message.Value;')
    [void]$hb.AppendLine('        return default;')
    [void]$hb.AppendLine('    }')
    [void]$hb.AppendLine('')
}

[void]$hb.AppendLine('}')
Set-Content -Path $handlerPath -Value $hb.ToString() -Encoding UTF8
Write-Output "Wrote handler with $Count implementations to $handlerPath"
